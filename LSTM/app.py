"""Streamlit app for Hamlet next-word prediction."""
import pickle
from pathlib import Path

import numpy as np
import streamlit as st
from tensorflow.keras.models import load_model
from tensorflow.keras.preprocessing.sequence import pad_sequences

# App configuration
st.set_page_config(
    page_title="Hamlet Next-Word Prediction",
    page_icon="📖",
    layout="centered",
)

st.title("📖 Hamlet Next-Word Prediction")
st.write("Generate text using an LSTM trained on Shakespeare's *Hamlet*.")

BASE_DIR = Path(__file__).resolve().parent
ARTIFACTS_DIR = BASE_DIR / "deployment_artifacts"
MODEL_PATH = ARTIFACTS_DIR / "next_word_lstm.keras"
TOKENIZER_PATH = ARTIFACTS_DIR / "tokenizer.pickle"

if not MODEL_PATH.exists():
    MODEL_PATH = BASE_DIR / "next_word_lstm.keras"
if not TOKENIZER_PATH.exists():
    TOKENIZER_PATH = BASE_DIR / "tokenizer.pickle"

MAX_SEQUENCE_LEN = 14


@st.cache_resource
def load_prediction_resources():
    model = load_model(MODEL_PATH)

    with open(TOKENIZER_PATH, "rb") as file:
        tokenizer = pickle.load(file)

    return model, tokenizer


def predict_next_word(model, tokenizer, text):
    token_list = tokenizer.texts_to_sequences([text])[0]

    if not token_list:
        return None

    token_list = token_list[-(MAX_SEQUENCE_LEN - 1):]
    token_list = pad_sequences(
        [token_list],
        maxlen=MAX_SEQUENCE_LEN - 1,
        padding="pre",
    )

    probabilities = model.predict(token_list, verbose=0)
    predicted_index = int(np.argmax(probabilities, axis=1)[0])

    return tokenizer.index_word.get(predicted_index)


if not MODEL_PATH.exists() or not TOKENIZER_PATH.exists():
    st.error(
        "The model or tokenizer is missing. Add both files to "
        "LSTM/deployment_artifacts/ before deploying."
    )
    st.stop()

try:
    model, tokenizer = load_prediction_resources()
except Exception as exc:
    st.error(f"Could not load the model or tokenizer: {exc}")
    st.stop()

starting_text = st.text_input(
    "Enter a starting sentence",
    value="to be or not to be",
)

num_words = st.slider(
    "Number of words to generate",
    min_value=1,
    max_value=20,
    value=5,
)

if st.button("Generate text", type="primary"):
    if not starting_text.strip():
        st.warning("Please enter a starting sentence.")
    else:
        generated_text = starting_text.strip()

        for _ in range(num_words):
            next_word = predict_next_word(
                model,
                tokenizer,
                generated_text,
            )

            if next_word is None:
                st.warning("Unable to predict a next word for this input.")
                break

            generated_text += " " + next_word

        st.subheader("Generated text")
        st.write(generated_text)

st.caption(
    "Educational project: predictions are generated by an LSTM "
    "trained on text from Shakespeare's Hamlet."
)
